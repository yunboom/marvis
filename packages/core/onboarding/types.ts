/**
 * Questionnaire answers collected while creating a workspace.
 * use_case is multi-select; role is single-select. Explicit *_skipped flags
 * distinguish declines from unanswered fields.
 *
 * Version 2 remains the shared analytics cohort; the JSONB storage is schema-less.
 */
export interface QuestionnaireAnswers {
  role: Role | null;
  role_other: string | null;
  role_skipped: boolean;
  use_case: UseCase[];
  use_case_other: string | null;
  use_case_skipped: boolean;
  version: 2;
}
