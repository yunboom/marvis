#!/usr/bin/env bash
# Regenerates server/schema.sql: the full schema after every migration,
# dumped from a throwaway database so test fixtures never leak into it.
# The file is a read-only reference; migrations remain the source of truth.
set -euo pipefail

ENV_FILE="${1:-.env}"
OUT="server/schema.sql"

set -a
# shellcheck disable=SC1090
. "$ENV_FILE"
set +a

POSTGRES_USER="${POSTGRES_USER:-marvis}"
POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-marvis}"
POSTGRES_PORT="${POSTGRES_PORT:-5432}"
SNAPSHOT_DB="schema_dump_tmp_$$"

pg() {
  docker compose exec -T postgres "$@"
}

MIGRATE_LOG="$(mktemp)"

pg createdb -U "$POSTGRES_USER" "$SNAPSHOT_DB"
trap 'pg dropdb -U "$POSTGRES_USER" --if-exists "$SNAPSHOT_DB" >/dev/null; rm -f "$MIGRATE_LOG"' EXIT

if ! (cd server && DATABASE_URL="postgres://$POSTGRES_USER:$POSTGRES_PASSWORD@localhost:$POSTGRES_PORT/$SNAPSHOT_DB?sslmode=disable" \
  go run ./cmd/migrate up >"$MIGRATE_LOG" 2>&1); then
  cat "$MIGRATE_LOG"
  exit 1
fi

# \restrict keys are random per dump and the version banner changes with the
# image, so both are dropped to keep regenerations diff-free.
{
  echo "-- Code generated by \`make schema\`. DO NOT EDIT."
  echo "-- Full schema after all migrations in server/migrations/."
  pg pg_dump -U "$POSTGRES_USER" --schema-only --no-owner --no-privileges "$SNAPSHOT_DB" |
    sed -E '/^\\(un)?restrict /d; /^-- Dumped (from|by) /d' |
    cat -s
} >"$OUT"

echo "Wrote $OUT"
